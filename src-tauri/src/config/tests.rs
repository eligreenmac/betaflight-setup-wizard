fn fixtures() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

fn model(name: &str) -> DroneModel {
    let p = fixtures().join(format!("models/{name}.json"));
    let text = std::fs::read_to_string(&p).unwrap();
    serde_json::from_str(&text).unwrap()
}

fn board_for(name: &str) -> &'static str {
    if name.starts_with("whoop") {
        "crazybeef4sx1280"
    } else {
        "speedybeef405v4"
    }
}

fn firmware_dir(d: Dialect) -> &'static str {
    d.as_str()
}

fn tmp_store(tag: &str) -> BackupStore {
    let dir = std::env::temp_dir().join(format!("bfsw-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    BackupStore::new(dir)
}

