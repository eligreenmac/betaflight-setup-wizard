/// Golden files: plan output against the fixture FC for each supported dialect.
/// Regenerate with `UPDATE_GOLDEN=1 cargo test golden`.
#[test]
fn golden_files() {
    let update = std::env::var_os("UPDATE_GOLDEN").is_some();
    let mut failures = Vec::new();
    for (name, dialects) in GOLDEN {
        let m = model(name);
        for &d in *dialects {
            let fc = MockFc::load(firmware_dir(d), board_for(name));
            let snap = fc.snapshot();
            let script = generate_for(&m, d, &snap.ports, Some(&snap)).unwrap();
            let mut text = format!(
                "# golden: {name} on {} ({}); generated by config::generate, do not edit\n",
                fc.board_name, fc.version
            );
            for w in &script.warnings {
                text += &format!("# warning: {w}\n");
            }
            for c in &script.commands {
                text += c;
                text.push('\n');
            }
            let path = fixtures().join(format!("golden/{name}.{}.cli", d.as_str()));
            if update {
                std::fs::write(&path, &text).unwrap();
            } else {
                let want = std::fs::read_to_string(&path).unwrap_or_default();
                if want.replace("\r\n", "\n") != text {
                    failures.push(path.display().to_string());
                }
            }
        }
    }
    assert!(
        failures.is_empty(),
        "golden mismatch (UPDATE_GOLDEN=1 to regenerate): {failures:?}"
    );
}

#[test]
fn dialect_differences() {
    let m = model("freestyle-5in-analog");
    for d in Dialect::ALL {
        let mut fc = MockFc::load(d.as_str(), "speedybeef405v4");
        // The SpeedyBee board file already puts serial RX on UART2; clear it so the
        // dialect-specific command is emitted.
        fc.preset(&[if d == Dialect::V2025_12 {
            "serial UART2 0 115200 57600 0 115200"
        } else {
            "serial 1 0 115200 57600 0 115200"
        }]);
        let snap = fc.snapshot();
        let s = generate_for(&m, d, &snap.ports, Some(&snap)).unwrap();
        let has = |x: &str| s.commands.iter().any(|c| c == x);
        if d == Dialect::V2025_12 {
            assert!(has("serial UART2 64 115200 57600 0 115200"));
            assert!(!has("feature -RX_MSP"));
        } else {
            assert!(has("serial 1 64 115200 57600 0 115200"));
            assert!(has("feature -RX_MSP"));
        }
        // GPS port gets 115200 GPS baud.
        assert!(s
            .commands
            .iter()
            .any(|c| c.starts_with("serial") && c.contains(" 2 115200 115200 0 115200")));
        assert!(has("feature TELEMETRY"));
    }
}

