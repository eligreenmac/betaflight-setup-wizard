#[test]
fn msp_displayport_rules() {
    let mut fc = MockFc::load("4.5", "speedybeef405v4");
    // Old config: DJI on UART3 (MSP|VTX_MSP), user moves it to UART1.
    fc.preset(&["serial 2 131073 115200 57600 0 115200"]);
    let s = session::plan(&mut fc, &model("cinematic-7in-hd")).unwrap();
    assert!(s
        .commands
        .contains(&"serial 0 131073 115200 57600 0 115200".to_string()));
    assert!(s
        .commands
        .contains(&"serial 2 0 115200 57600 0 115200".to_string()));
    let c = s.cleared.iter().find(|c| c.port == "UART3").unwrap();
    assert_eq!(c.function_mask_after, 0);

    // MSP that the user configured themselves (MSP|VTX_MSP|BLACKBOX? no: plain MSP + VTX_MSP
    // plus another function) is kept.
    let mut fc = MockFc::load("4.5", "speedybeef405v4");
    // MSP|BLACKBOX|VTX_MSP on UART3; the board-default MSP on UART4 was freed by the user,
    // otherwise VCP + UART1 + UART3 + UART4 would be 4 MSP ports (Betaflight allows 3).
    fc.preset(&[
        "serial 2 131201 115200 57600 0 115200",
        "serial 3 0 115200 57600 0 115200",
    ]);
    let s = session::plan(&mut fc, &model("cinematic-7in-hd")).unwrap();
    assert!(s
        .commands
        .contains(&"serial 2 129 115200 57600 0 115200".to_string()));
}

