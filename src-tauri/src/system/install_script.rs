//! The elevated part of `system_install_dfu_driver`, as a Windows PowerShell
//! script passed on the command line of `%SystemRoot%\System32\...\powershell.exe`
//! started with `runas` (one UAC prompt for all devices).
//!
//! Why not run `bfsw-wdi-simple.exe --dest %TEMP%\...` directly: %TEMP% is writable
//! by the (non-elevated) user, so other code running as the user could swap the
//! extracted .inf/.cat/co-installer files between extraction and installation.
//! The script instead, running elevated:
//! 1. creates a fresh per-run directory `%ProgramData%\BFSW-WinUSB-<run id>` with a
//!    protected DACL that only grants SYSTEM and Administrators (owner Administrators),
//!    refusing to continue if the directory already existed, the ACL is not exactly
//!    that, or the directory is not empty;
//! 2. copies the bundled helper into it and runs it from there (one run per VID/PID,
//!    `--dest <dir>\<vid>_<pid>`), stopping at the first failure;
//! 3. always deletes the directory.
//!
//! Exit code: 0, the helper's libwdi `wdi_error` (negative), or one of the
//! `EXIT_*` codes below. Pure string building, unit-tested on every OS; the Windows
//! test runs the script for real (CI runners are elevated).

use super::usb_drivers::wdi_simple_args;

pub const EXIT_NO_PROGRAMDATA: i32 = 1001;
pub const EXIT_DIR_EXISTS: i32 = 1002;
pub const EXIT_DIR_CREATE: i32 = 1003;
pub const EXIT_DIR_INSECURE: i32 = 1004;
pub const EXIT_DIR_NOT_EMPTY: i32 = 1005;
pub const EXIT_COPY_HELPER: i32 = 1006;
pub const EXIT_SCRIPT_ERROR: i32 = 1007;

/// Owner Administrators, protected DACL: full control for SYSTEM and
/// Administrators only (inherited by everything created inside).
pub const SECURE_DIR_SDDL: &str = "O:BAD:P(A;OICI;FA;;;SY)(A;OICI;FA;;;BA)";

/// Name prefix of the per-run directory under %ProgramData%.
pub const DIR_PREFIX: &str = "BFSW-WinUSB-";

/// PowerShell single-quoted literal (no expansion; `'` doubled). Also doubles the
/// typographic quotes PowerShell treats as `'`.
pub fn ps_quote(s: &str) -> String {
    let mut out = String::from("'");
    for c in s.chars() {
        if matches!(c, '\'' | '\u{2018}' | '\u{2019}' | '\u{201A}' | '\u{201B}') {
            out.push(c);
        }
        out.push(c);
    }
    out.push('\'');
    out
}

/// Human message for a non-zero script exit code (libwdi codes included).
pub fn exit_message(code: i32) -> String {
    match code {
        EXIT_NO_PROGRAMDATA => "could not locate %ProgramData%".into(),
        EXIT_DIR_EXISTS => "the driver work folder already exists; retry".into(),
        EXIT_DIR_CREATE => "could not create the protected driver work folder".into(),
        EXIT_DIR_INSECURE => {
            "the driver work folder does not have the expected admin-only permissions".into()
        }
        EXIT_DIR_NOT_EMPTY => "the driver work folder was tampered with (not empty)".into(),
        EXIT_COPY_HELPER => "could not copy the driver helper into its work folder".into(),
        EXIT_SCRIPT_ERROR => "the elevated driver installer failed unexpectedly".into(),
        c => format!("{} (libwdi {c})", super::usb_drivers::wdi_error_message(c)),
    }
}

/// Build the script. `run_id` must be `[0-9a-f]+` (generated by the caller).
/// `devices`: (vid, pid, friendly name) to bind to WinUSB.
pub fn install_script(helper: &str, run_id: &str, devices: &[(u16, u16, String)]) -> String {
    debug_assert!(!run_id.is_empty() && run_id.bytes().all(|b| b.is_ascii_hexdigit()));
    let mut s = String::new();
    let mut line = |l: &str| {
        s.push_str(l);
        s.push('\n');
    };
    line("$ErrorActionPreference = 'Stop'");
    line("$rc = 0");
    line("$d = $null");
    // Only a directory we created and verified is ever deleted (never follow a
    // junction someone else planted).
    line("$mine = $false");
    line("try {");
    line("  $base = [Environment]::GetFolderPath('CommonApplicationData')");
    line(&format!(
        "  if (-not $base) {{ exit {EXIT_NO_PROGRAMDATA} }}"
    ));
    line(&format!(
        "  $d = Join-Path $base {}",
        ps_quote(&format!("{DIR_PREFIX}{run_id}"))
    ));
    line(&format!(
        "  if (Test-Path -LiteralPath $d) {{ $d = $null; exit {EXIT_DIR_EXISTS} }}"
    ));
    line("  try {");
    line("    $sd = New-Object System.Security.AccessControl.DirectorySecurity");
    line(&format!(
        "    $sd.SetSecurityDescriptorSddlForm({})",
        ps_quote(SECURE_DIR_SDDL)
    ));
    line("    [void][System.IO.Directory]::CreateDirectory($d, $sd)");
    line(&format!("  }} catch {{ exit {EXIT_DIR_CREATE} }}"));
    // Verify instead of trusting: protected DACL, owner + every ACE is SYSTEM or
    // Administrators, nothing inside yet.
    line("  $ok = @('S-1-5-18', 'S-1-5-32-544')");
    line("  $acl = Get-Acl -LiteralPath $d");
    line("  $sid = [System.Security.Principal.SecurityIdentifier]");
    line("  $owner = $acl.GetOwner($sid).Value");
    line("  $rules = @($acl.GetAccessRules($true, $true, $sid))");
    line("  $bad = @($rules | Where-Object { $ok -notcontains $_.IdentityReference.Value -or $_.IsInherited })");
    line("  $reparse = ((Get-Item -LiteralPath $d -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0");
    line(&format!(
        "  if ($reparse -or -not $acl.AreAccessRulesProtected -or $ok -notcontains $owner -or $rules.Count -eq 0 -or $bad.Count -ne 0) {{ exit {EXIT_DIR_INSECURE} }}"
    ));
    line(&format!(
        "  if (@(Get-ChildItem -Force -LiteralPath $d).Count -ne 0) {{ exit {EXIT_DIR_NOT_EMPTY} }}"
    ));
    line("  $mine = $true");
    line(&format!(
        "  $exe = Join-Path $d {}",
        ps_quote(super::HELPER_EXE)
    ));
    line(&format!(
        "  try {{ Copy-Item -LiteralPath {} -Destination $exe }} catch {{ exit {EXIT_COPY_HELPER} }}",
        ps_quote(helper)
    ));
    for (vid, pid, name) in devices {
        let dest_marker = "\u{0}DEST\u{0}";
        let args = wdi_simple_args(*vid, *pid, name, dest_marker)
            .iter()
            .map(|a| {
                if a == dest_marker {
                    format!(
                        "(Join-Path $d {})",
                        ps_quote(&format!("{vid:04x}_{pid:04x}"))
                    )
                } else {
                    ps_quote(a)
                }
            })
            .collect::<Vec<_>>()
            .join(" ");
        // 'Continue' so helper stderr output never turns into a terminating error.
        line("  $ErrorActionPreference = 'Continue'");
        line(&format!("  & $exe {args}"));
        line("  $code = $LASTEXITCODE");
        line("  $ErrorActionPreference = 'Stop'");
        line("  if ($code -ne 0) { $rc = $code; exit $rc }");
    }
    line(&format!(
        "}} catch {{ [Console]::Error.WriteLine(($_ | Out-String)); $rc = {EXIT_SCRIPT_ERROR}; exit $rc }}"
    ));
    line("finally {");
    line("  if ($mine -and (Test-Path -LiteralPath $d)) { Remove-Item -LiteralPath $d -Recurse -Force -ErrorAction SilentlyContinue }");
    line("}");
    line("exit $rc");
    s
}

/// `powershell.exe` parameters that run `script` (hidden, no profile, no prompts).
/// The script never contains `"`, so wrapping it in one quoted argument is exact.
pub fn powershell_params(script: &str) -> Option<String> {
    if script.contains('"') {
        return None;
    }
    // Newlines stay inside the quoted argument (CommandLineToArgvW only splits on
    // unquoted spaces/tabs); they are needed between `}` and `catch`/`finally`.
    Some(format!(
        "-NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -Command \"{script}\""
    ))
}

/// Per-run id: hex of time + pid (uniqueness only; security comes from the ACL
/// check, not from unpredictability).
pub fn run_id() -> String {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or_default();
    format!("{:x}{:x}", nanos, std::process::id())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn devs() -> Vec<(u16, u16, String)> {
        vec![
            (0x0483, 0xDF11, "STM32 DFU".into()),
            (0x2E3C, 0xDF11, "AT32 DFU".into()),
        ]
    }

    #[test]
    fn quoting() {
        assert_eq!(ps_quote("a b"), "'a b'");
        assert_eq!(ps_quote("it's"), "'it''s'");
        assert_eq!(ps_quote("x\u{2019}y"), "'x\u{2019}\u{2019}y'");
        assert_eq!(ps_quote("$env:TEMP"), "'$env:TEMP'");
    }

    #[test]
    fn script_uses_admin_only_programdata_dir_not_temp() {
        let s = install_script(
            r"C:\Program Files\BFSW\drivers\bfsw-wdi-simple.exe",
            "abc123",
            &devs(),
        );
        assert!(s.contains("GetFolderPath('CommonApplicationData')"));
        assert!(s.contains("'BFSW-WinUSB-abc123'"));
        assert!(s.contains(SECURE_DIR_SDDL));
        assert!(s.contains("AreAccessRulesProtected"));
        assert!(!s.to_ascii_lowercase().contains("temp"));
        assert!(!s.contains('"'));
        // helper is copied into the protected dir and run from there
        assert!(s.contains(r"Copy-Item -LiteralPath 'C:\Program Files\BFSW\drivers\bfsw-wdi-simple.exe' -Destination $exe"));
        assert_eq!(s.matches("& $exe ").count(), 2);
        assert!(s.contains("(Join-Path $d '0483_df11')"));
        assert!(s.contains("(Join-Path $d '2e3c_df11')"));
        assert!(s.contains("'--vid' '0x0483' '--pid' '0xDF11'"));
        assert!(s.contains("'STM32 DFU (Betaflight Setup Wizard)'"));
        // cleanup always runs
        assert!(s.contains("finally {"));
        assert!(s.contains("if ($mine -and"));
        assert!(s.contains("ReparsePoint"));
        assert!(s.contains("Remove-Item -LiteralPath $d -Recurse -Force"));
    }

    #[test]
    fn hostile_names_stay_literal() {
        let s = install_script(
            r"C:\it's\x.exe",
            "1",
            &[(1, 2, "a'; Remove-Item C:\\ #".into())],
        );
        assert!(s.contains(r"'C:\it''s\x.exe'"));
        assert!(s.contains("'a''; Remove-Item C:\\ # (Betaflight Setup Wizard)'"));
    }

    #[test]
    fn params_and_messages() {
        let p = powershell_params("exit 0").unwrap();
        assert!(p.starts_with("-NoLogo -NoProfile -NonInteractive"));
        assert!(p.ends_with("-Command \"exit 0\""));
        assert!(powershell_params("echo \"x\"").is_none());
        assert!(exit_message(EXIT_DIR_INSECURE).contains("admin-only"));
        assert!(exit_message(-14).contains("cancelled by user"));
        let id = run_id();
        assert!(!id.is_empty() && id.bytes().all(|b| b.is_ascii_hexdigit()));
    }

    /// Runs the real script (GitHub's Windows runners are elevated): the protected
    /// dir is created, verified, the "helper" (whoami.exe, which rejects our args)
    /// runs from it, its exit code comes back and the dir is removed.
    #[cfg(windows)]
    #[test]
    fn script_runs_on_windows() {
        use std::os::windows::process::CommandExt;
        let sys = std::env::var("SystemRoot").unwrap_or_else(|_| r"C:\Windows".into());
        let ps = format!(r"{sys}\System32\WindowsPowerShell\v1.0\powershell.exe");
        let whoami = format!(r"{sys}\System32\whoami.exe");
        let id = run_id();
        let base = std::env::var("ProgramData").unwrap_or_else(|_| r"C:\ProgramData".into());
        let dir = std::path::Path::new(&base).join(format!("{DIR_PREFIX}{id}"));

        let run = |devices: &[(u16, u16, String)]| -> i32 {
            let script = install_script(&whoami, &id, devices);
            // Exactly the parameters the app passes to the elevated launch.
            let params = powershell_params(&script).expect("no quotes");
            let out = std::process::Command::new(&ps)
                .raw_arg(&params)
                .output()
                .expect("powershell runs");
            eprintln!("{}", String::from_utf8_lossy(&out.stdout));
            eprintln!("{}", String::from_utf8_lossy(&out.stderr));
            out.status.code().expect("exit code")
        };
        // No devices: create + verify + copy + cleanup.
        assert_eq!(run(&[]), 0);
        assert!(!dir.exists());
        // whoami rejects wdi-simple's args -> non-zero propagated, dir still removed.
        let code = run(&[(0x0483, 0xDF11, "STM32 DFU".into())]);
        assert!(code != 0 && code < 1000, "unexpected exit {code}");
        assert!(!dir.exists());
        // Pre-existing dir is refused.
        std::fs::create_dir_all(&dir).expect("mkdir");
        assert_eq!(run(&[]), EXIT_DIR_EXISTS);
        assert!(dir.exists(), "a dir we did not create is left alone");
        std::fs::remove_dir_all(&dir).expect("cleanup");
    }
}
