// Maintains src-tauri/windows/installer.nsi (bundle.windows.nsis.template): Tauri's own
// NSIS template for the locked @tauri-apps/cli version, with one change. VIProductVersion
// (and VIFileVersion) are derived from the app version like the MSI
// (X.Y.Z-N -> X.Y.Z.N, X.Y.Z -> X.Y.Z.0) instead of Tauri's VERSIONWITHBUILD, which only
// uses semver build metadata (so 0.1.0-1 became 0.1.0.0). installerHooks cannot do this:
// they are !included before VERSIONWITHBUILD is !defined and before VIProductVersion is set,
// and NSIS rejects redefining either.
//
//   node src-tauri/windows/nsis-template.mjs --write   # after bumping @tauri-apps/cli
//   node src-tauri/windows/nsis-template.mjs --check   # CI: fails if out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "installer.nsi");
const lock = JSON.parse(readFileSync(join(here, "..", "..", "package-lock.json"), "utf8"));
const cli = lock.packages["node_modules/@tauri-apps/cli"].version;
const url = `https://raw.githubusercontent.com/tauri-apps/tauri/tauri-cli-v${cli}/crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi`;

const ORIGINAL = 'VIProductVersion "${VERSIONWITHBUILD}"';
const REPLACEMENT = [
  "; bfsw: numeric version like the MSI: X.Y.Z-N -> X.Y.Z.N, X.Y.Z -> X.Y.Z.0",
  '; (appending "-0-" makes BFSW_VPRE the pre-release number, or 0 for a release).',
  '!searchparse "${VERSION}-0-" "" BFSW_VBASE "-" BFSW_VPRE "-"',
  '!define BFSW_VNUMERIC "${BFSW_VBASE}.${BFSW_VPRE}"',
  'VIProductVersion "${BFSW_VNUMERIC}"',
  'VIFileVersion "${BFSW_VNUMERIC}"',
].join("\n");

function header() {
  return [
    `; Generated by src-tauri/windows/nsis-template.mjs from Tauri's NSIS template`,
    `; (tauri-cli v${cli}, MIT OR Apache-2.0, ${url}).`,
    `; Only change: VIProductVersion/VIFileVersion (search "bfsw:"). Do not edit by hand;`,
    `; re-run the script with --write after updating @tauri-apps/cli.`,
    "",
  ].join("\n");
}

const res = await fetch(url);
if (!res.ok) throw new Error(`GET ${url}: ${res.status}`);
const upstream = (await res.text()).replace(/\r\n/g, "\n");
const count = upstream.split(ORIGINAL).length - 1;
if (count !== 1) {
  console.error(`::error::upstream template (tauri-cli v${cli}) has ${count} '${ORIGINAL}' lines, expected 1; update nsis-template.mjs`);
  process.exit(1);
}
const generated = header() + upstream.replace(ORIGINAL, REPLACEMENT);

const mode = process.argv[2];
if (mode === "--write") {
  writeFileSync(out, generated);
  console.log(`wrote ${out} from tauri-cli v${cli}`);
} else if (mode === "--check") {
  const current = readFileSync(out, "utf8").replace(/\r\n/g, "\n");
  if (current !== generated) {
    console.error(`::error::src-tauri/windows/installer.nsi is not Tauri's template for tauri-cli v${cli} + the bfsw change; run: node src-tauri/windows/nsis-template.mjs --write`);
    process.exit(1);
  }
  console.log(`installer.nsi matches tauri-cli v${cli}'s template + the bfsw version change`);
} else {
  console.error("usage: nsis-template.mjs --write | --check");
  process.exit(2);
}
