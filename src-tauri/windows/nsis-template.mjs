// Maintains src-tauri/windows/installer.nsi (bundle.windows.nsis.template): Tauri's own
// NSIS template for the locked @tauri-apps/cli version, with one change. VIProductVersion
// (and VIFileVersion) are derived from the app version like the MSI
// (X.Y.Z-N -> X.Y.Z.N, X.Y.Z -> X.Y.Z.0) instead of Tauri's VERSIONWITHBUILD, which only
// uses semver build metadata (so 0.1.0-1 became 0.1.0.0). installerHooks cannot do this:
// they are !included before VERSIONWITHBUILD is !defined and before VIProductVersion is set,
// and NSIS rejects redefining either.
//
// The unmodified upstream template is vendored in windows/upstream/installer.nsi and pinned
// (tauri-cli version, tauri-bundler version, URL, SHA-256) in windows/nsis-template.lock.json,
// so the check needs no network.
//
//   node src-tauri/windows/nsis-template.mjs --check     # CI, offline: pin matches the
//                                                        # locked CLI, vendored copy matches
//                                                        # the pinned hash, installer.nsi is
//                                                        # vendored copy + the bfsw change
//   node src-tauri/windows/nsis-template.mjs --write     # offline: regenerate installer.nsi
//                                                        # from the vendored copy
//   node src-tauri/windows/nsis-template.mjs --refresh   # network, opt-in: after bumping
//                                                        # @tauri-apps/cli, re-download the
//                                                        # template, update the vendored copy,
//                                                        # the pin and installer.nsi
//   node src-tauri/windows/nsis-template.mjs --verify-upstream  # network, opt-in, read-only:
//                                                        # upstream still matches the pin
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "installer.nsi");
const vendored = join(here, "upstream", "installer.nsi");
const pinFile = join(here, "nsis-template.lock.json");
const rel = (p) => p.slice(join(here, "..", "..").length + 1).replace(/\\/g, "/");

const lock = JSON.parse(readFileSync(join(here, "..", "..", "package-lock.json"), "utf8"));
const lockedCli = lock.packages["node_modules/@tauri-apps/cli"].version;
const RAW = (cli) => `https://raw.githubusercontent.com/tauri-apps/tauri/tauri-cli-v${cli}`;
const templateUrl = (cli) => `${RAW(cli)}/crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi`;

const ORIGINAL = 'VIProductVersion "${VERSIONWITHBUILD}"';
const REPLACEMENT = [
  "; bfsw: numeric version like the MSI: X.Y.Z-N -> X.Y.Z.N, X.Y.Z -> X.Y.Z.0",
  '; (appending "-0-" makes BFSW_VPRE the pre-release number, or 0 for a release).',
  '!searchparse "${VERSION}-0-" "" BFSW_VBASE "-" BFSW_VPRE "-"',
  '!define BFSW_VNUMERIC "${BFSW_VBASE}.${BFSW_VPRE}"',
  'VIProductVersion "${BFSW_VNUMERIC}"',
  'VIFileVersion "${BFSW_VNUMERIC}"',
].join("\n");

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const fail = (msg) => {
  console.error(`::error::${msg}`);
  process.exit(1);
};

function generate(upstreamBuf, cli) {
  const upstream = upstreamBuf.toString("utf8").replace(/\r\n/g, "\n");
  const count = upstream.split(ORIGINAL).length - 1;
  if (count !== 1) {
    fail(`upstream template (tauri-cli v${cli}) has ${count} '${ORIGINAL}' lines, expected 1; update nsis-template.mjs`);
  }
  const header = [
    `; Generated by src-tauri/windows/nsis-template.mjs from Tauri's NSIS template`,
    `; (tauri-cli v${cli}, MIT OR Apache-2.0, ${templateUrl(cli)}).`,
    `; Only change: VIProductVersion/VIFileVersion (search "bfsw:"). Do not edit by hand;`,
    `; after updating @tauri-apps/cli run the script with --refresh.`,
    "",
  ].join("\n");
  return header + upstream.replace(ORIGINAL, REPLACEMENT);
}

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url}: ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

const readPin = () => JSON.parse(readFileSync(pinFile, "utf8"));
const mode = process.argv[2];

if (mode === "--check" || mode === "--write") {
  const pin = readPin();
  if (pin.tauriCli !== lockedCli) {
    fail(`${rel(pinFile)} pins tauri-cli v${pin.tauriCli} but package-lock.json has @tauri-apps/cli ${lockedCli}; run: node src-tauri/windows/nsis-template.mjs --refresh`);
  }
  const buf = readFileSync(vendored);
  const actual = sha256(buf);
  if (actual !== pin.sha256) {
    fail(`${rel(vendored)} sha256 ${actual} != pinned ${pin.sha256} (tauri-cli v${pin.tauriCli}); the vendored upstream copy must not be edited, run: node src-tauri/windows/nsis-template.mjs --refresh`);
  }
  const generated = generate(buf, pin.tauriCli);
  if (mode === "--write") {
    writeFileSync(out, generated);
    console.log(`wrote ${rel(out)} from the vendored tauri-cli v${pin.tauriCli} template`);
  } else {
    const current = readFileSync(out, "utf8").replace(/\r\n/g, "\n");
    if (current !== generated) {
      fail(`${rel(out)} is not Tauri's template for tauri-cli v${pin.tauriCli} + the bfsw change; run: node src-tauri/windows/nsis-template.mjs --write`);
    }
    console.log(`installer.nsi matches tauri-cli v${pin.tauriCli}'s template (tauri-bundler ${pin.tauriBundler}, sha256 ${pin.sha256}) + the bfsw version change (offline)`);
  }
} else if (mode === "--refresh") {
  const url = templateUrl(lockedCli);
  const buf = await get(url);
  const bundlerToml = (await get(`${RAW(lockedCli)}/crates/tauri-bundler/Cargo.toml`)).toString("utf8");
  const tauriBundler = /^version\s*=\s*"([^"]+)"/m.exec(bundlerToml)?.[1];
  if (!tauriBundler) throw new Error("could not read tauri-bundler version");
  const generated = generate(buf, lockedCli);
  const pin = { tauriCli: lockedCli, tauriBundler, url, sha256: sha256(buf) };
  mkdirSync(dirname(vendored), { recursive: true });
  writeFileSync(vendored, buf);
  writeFileSync(pinFile, JSON.stringify(pin, null, 2) + "\n");
  writeFileSync(out, generated);
  console.log(`refreshed from tauri-cli v${lockedCli} (tauri-bundler ${tauriBundler}), sha256 ${pin.sha256}`);
} else if (mode === "--verify-upstream") {
  const pin = readPin();
  const actual = sha256(await get(pin.url));
  if (actual !== pin.sha256) fail(`upstream ${pin.url} sha256 ${actual} != pinned ${pin.sha256}`);
  console.log(`upstream template for tauri-cli v${pin.tauriCli} still matches the pin (${pin.sha256})`);
} else {
  console.error("usage: nsis-template.mjs --check | --write | --refresh | --verify-upstream");
  process.exit(2);
}
